"""
uncued_benchmark.py - writes the frozen uncued-names benchmark (data/hard_cases/uncued.txt): short
clinical narratives with names where no cue gives them away (no "Patient:", "Dr", "Mr", "Next of kin"),
relatives, consent notes, lower case, and Chinese, Malay, Indian and Western names, plus a few
negatives (capitalised clinical wording, no name) for false alarms.

Names come from invented pools here, not from PrivLab's name lists. The set is frozen: this script
refuses to overwrite it, and its SHA-256 goes to eval/uncued.sha256, which score_deid checks before
every run. Never tune rules on it (PLAN.md, Day 7); report every case, not only the ones Layer 2 wins.

Usage:
  python -m eval.uncued_benchmark            # once; then score:
  python -m eval.score_deid --split uncued [--mode patterns|pipeline|spark]
"""
import hashlib
import random
import sys

from common.config import ROOT

OUT = ROOT / "data" / "hard_cases" / "uncued.txt"
HASH = ROOT / "eval" / "uncued.sha256"
SEED = 20261030

NAMES = {
    "Chinese": ["Tan Mei Ling", "Lim Wei Jie", "Goh Siew Hoon", "Chua Boon Keng", "Ng Hui Min", "Teo Kah Seng",
                "Ho Li Ting", "Koh Jun Hao"],
    "Malay": ["Nurul Huda binte Ismail", "Ahmad Faiz bin Rahman", "Siti Aishah binte Kamal",
              "Muhammad Hafiz bin Yusof", "Farah Nadia binte Osman", "Zulkifli bin Hamid"],
    "Indian": ["Arjun Krishnan", "Kavitha Ramasamy", "Suresh a/l Pillai", "Deepa Menon", "Vikram Subramaniam",
               "Lakshmi d/o Narayanan"],
    "Western": ["Oliver Hughes", "Emily Carter", "James Whitfield", "Sophie Brennan", "Daniel Moreau",
                "Hannah Fischer"],
}
TEMPLATES = [                                   # {a}, {b}: names; never a cue word before them
    "{a} consented to the procedure after discussion with the team.",
    "The family, including {a}, were updated on the findings.",
    "Results were discussed with {a} by phone this afternoon.",
    "Consent for additional immunostains was obtained from {a}.",
    "Accompanied by {a}, who interpreted for the patient.",
    "Per {a}, the lump was first noticed three months ago.",
    "Telephone report given to {a} at 14:30.",
    "{a} asked that {b} collect the results on her behalf.",
    "Biopsy was arranged after {a} raised concern about a palpable mass.",
    "History obtained from {a} and confirmed with {b}.",
    "Specimen labelled for {a} on the request form.",
    "A copy was requested by {a} for the insurer.",
]
NEGATIVES = [
    "Results were discussed at the Breast Multidisciplinary Team meeting.",
    "Gleason pattern 4 was confirmed on review by the Uropathology service.",
    "Margins were assessed according to the Royal College of Pathologists dataset.",
    "Immunohistochemistry was performed with the Ventana BenchMark platform.",
    "Frozen section was reported by the Anatomical Pathology on-call service.",
]


def build() -> str:
    rng = random.Random(SEED)
    groups = list(NAMES)
    pairs = [(g, t) for g in groups for t in TEMPLATES]  # every name group with every sentence once
    rng.shuffle(pairs)
    used = {g: 0 for g in groups}
    lines = ["# Uncued-names benchmark (frozen; generated by eval/uncued_benchmark.py, seed %d)." % SEED,
             "# Names without cues. Never tune rules on this set. All names are invented.", ""]
    by_group = {g: [] for g in groups}
    for i, (group, template) in enumerate(pairs):
        a = NAMES[group][used[group] % len(NAMES[group])]
        used[group] += 1
        other = rng.choice([g for g in groups if g != group])
        b = rng.choice(NAMES[other])
        lower = i % 5 == 4                       # every fifth case in lower case, as typed in a hurry
        mark = lambda n: f"[[NAME:{n.lower() if lower else n}]]"
        by_group[group].append(template.format(a=mark(a), b=mark(b)))
    for group, cases in by_group.items():
        lines += [f"# {group} names", *cases, ""]
    lines += ["# Negatives (no name)", *NEGATIVES, ""]
    return "\n".join(lines)


def digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def check_frozen() -> str | None:
    """None if the set matches its recorded hash, else the problem (score_deid refuses to run)."""
    if not OUT.exists() or not HASH.exists():
        return "uncued benchmark not generated: run python -m eval.uncued_benchmark"
    if digest(OUT.read_text(encoding="utf-8")) != HASH.read_text(encoding="utf-8").strip():
        return "uncued benchmark changed since it was frozen: restore data/hard_cases/uncued.txt"
    return None


def main() -> int:
    if OUT.exists():
        print(f"{OUT} exists and is frozen; not overwriting.", file=sys.stderr)
        return 1
    text = build()
    OUT.write_text(text, encoding="utf-8", newline="\n")
    HASH.write_text(digest(text) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({text.count('[[NAME:')} names) and {HASH}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
